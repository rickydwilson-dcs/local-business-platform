#!/usr/bin/env tsx
/**
 * Scaffold Client Site CLI
 *
 * Copies base-template, wires theme, generates content from brief data,
 * and verifies the dev server starts.
 *
 * Usage:
 *   npx tsx tools/scaffold-client-site.ts --theme corvus --trade events --brief output/briefs/abc123.json
 */

import * as fs from "fs";
import * as path from "path";
import * as child_process from "child_process";

import { JobBriefSchema, type JobBrief } from "./lib/pipeline-brief-types";

// ── Argument parsing ─────────────────────────────────────────────────────────

function parseArgs(): { theme?: string; trade?: string; brief?: string } {
  const args = process.argv.slice(2);
  const result: { theme?: string; trade?: string; brief?: string } = {};
  for (let i = 0; i < args.length; i++) {
    if (args[i] === "--theme" && args[i + 1]) result.theme = args[++i];
    else if (args[i] === "--trade" && args[i + 1]) result.trade = args[++i];
    else if (args[i] === "--brief" && args[i + 1]) result.brief = args[++i];
  }
  return result;
}

// ── File utilities ───────────────────────────────────────────────────────────

function copyDirRecursive(src: string, dest: string, exclude: string[] = []): void {
  fs.mkdirSync(dest, { recursive: true });
  for (const entry of fs.readdirSync(src, { withFileTypes: true })) {
    if (exclude.includes(entry.name)) continue;
    const srcPath = path.join(src, entry.name);
    const destPath = path.join(dest, entry.name);
    if (entry.isDirectory()) {
      copyDirRecursive(srcPath, destPath, exclude);
    } else {
      fs.copyFileSync(srcPath, destPath);
    }
  }
}

function findFilesRecursive(dir: string, extensions: string[], exclude: string[] = []): string[] {
  const results: string[] = [];
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    if (exclude.includes(entry.name)) continue;
    const fullPath = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      results.push(...findFilesRecursive(fullPath, extensions, exclude));
    } else if (extensions.some((ext) => entry.name.endsWith(ext))) {
      results.push(fullPath);
    }
  }
  return results;
}

function replaceInFile(filePath: string, replacements: Record<string, string>): void {
  if (!fs.existsSync(filePath)) return;
  let content = fs.readFileSync(filePath, "utf-8");
  for (const [from, to] of Object.entries(replacements)) {
    content = content.split(from).join(to);
  }
  fs.writeFileSync(filePath, content, "utf-8");
}

